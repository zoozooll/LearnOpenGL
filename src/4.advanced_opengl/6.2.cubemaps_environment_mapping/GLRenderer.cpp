GLRenderer::GLRenderer() :
    m_pShader(nullptr),
    m_pSkyboxShader(nullptr),
    camera(glm::vec3(0.0f, 0.0f, 3.0f)),
    lastX(SCR_WIDTH_DEFAULT / 2.0f),
    lastY(SCR_HEIGHT_DEFAULT / 2.0f),
    firstMouse(true),
    deltaTime(0.0f),
    lastFrame(0.0f),
    scrWidth(SCR_WIDTH_DEFAULT),
    scrHeight(SCR_HEIGHT_DEFAULT)
{
}

